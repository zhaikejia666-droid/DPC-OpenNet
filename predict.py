"""Predict known classes or anonymous unknown clusters from an existing checkpoint."""

from __future__ import annotations

import argparse
import csv
import importlib.util
import sys
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import DataLoader

from models.dpc_opennet import DPCOpenNet, DPCOpenNetConfig
from release_support import ROOT, resolve_device


def load_protocol(mode):
    case = "F2" if mode == "single" else "F2_F3"
    path = ROOT / "Experiment" / f"20shot_{case}_unknown.py"
    spec = importlib.util.spec_from_file_location("dpc_prediction_protocol", path)
    if spec is None or spec.loader is None:
        raise ImportError(path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def predict(checkpoint_path, input_path, output_path, device="auto", batch_size=32):
    device = resolve_device(device)
    # Checkpoints include NumPy and fitted sklearn state. Load only trusted files.
    checkpoint = torch.load(checkpoint_path, map_location=device, weights_only=False)
    if checkpoint.get("release_schema") != 1:
        raise ValueError("Use final_model.pt generated by this release; best_model.pt lacks calibration state.")
    mode = checkpoint["inference_mode"]
    protocol = load_protocol(mode)
    config = DPCOpenNetConfig(**{**checkpoint["config"], "device": str(device)})
    model = DPCOpenNet(config).to(device)
    model.load_state_dict(checkpoint["state_dict"])
    input_path = Path(input_path).resolve()
    paths = [input_path] if input_path.is_file() else sorted(input_path.rglob("*.csv"))
    if not paths or any(path.suffix.lower() != ".csv" for path in paths):
        raise ValueError("Input must be a numeric CSV sample or a directory containing CSV samples.")
    samples = [(path, "unlabeled") for path in paths]
    loader = DataLoader(protocol.FaultDataset(samples, {"unlabeled": 0}, config.input_length),
                        batch_size=batch_size, shuffle=False)
    data = protocol.collect(model, loader, device, checkpoint["known_means"], checkpoint["known_variances"])
    scores = protocol.novelty_score(data, checkpoint["score_normalizer"])
    if mode == "single":
        rejected = protocol.reject_mask(scores, data["known_prediction"], checkpoint["thresholds"])
    else:
        rejected = protocol.reject_mask(
            scores, data["known_prediction"], checkpoint["thresholds"],
            confidence=data["confidence"], confidence_thresholds=checkpoint["confidence_thresholds"],
            logit_margin=data["margin"], margin_thresholds=checkpoint["margin_thresholds"],
        )
        rescued, _ = protocol.weak_unknown_rescue_mask(
            data, scores, rejected, checkpoint["unknown_prototypes"], checkpoint["discovery_transform"],
            checkpoint["prototype_rescue_state"], checkpoint["known_supports"],
            checkpoint["prototype_rescue_ratio"], checkpoint["prototype_rescue_distance_scale"],
        )
        rejected |= rescued
    clusters = np.full(len(paths), -1, dtype=int)
    if rejected.any():
        clusters[rejected] = protocol.assign_unknown_clusters(
            data["spectral_embedding"][rejected], checkpoint["unknown_prototypes"], checkpoint["discovery_transform"]
        )
    known_classes = checkpoint["known_classes"]
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["file", "prediction", "rejected_as_unknown", "novelty_score"])
        for index, path in enumerate(paths):
            prediction = f"U{clusters[index]}" if rejected[index] else known_classes[int(data["known_prediction"][index])]
            writer.writerow([path.name if input_path.is_file() else path.relative_to(input_path).as_posix(),
                             prediction, bool(rejected[index]), float(scores[index])])
    return len(paths)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--checkpoint", type=Path, required=True)
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=ROOT / "results" / "predictions.csv")
    parser.add_argument("--device", default="auto")
    parser.add_argument("--batch-size", type=int, default=32)
    args = parser.parse_args()
    if args.batch_size < 1:
        parser.error("batch-size must be positive.")
    count = predict(args.checkpoint, args.input, args.output, args.device, args.batch_size)
    print(f"Saved {count} predictions to {args.output}")


if __name__ == "__main__":
    main()
